-- Parcours importation poussins : commande -> aeroport -> poulailler -> compartiment.
-- Le script ajoute des liens aux documents existants. Il ne modifie ni ne supprime
-- les donnees deja presentes.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    n NUMBER;
    PROCEDURE ajouter_colonne(p_table VARCHAR2, p_colonne VARCHAR2, p_definition VARCHAR2) IS
        n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME=UPPER(p_table) AND COLUMN_NAME=UPPER(p_colonne);
        IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_colonne || ' ' || p_definition || ')'; END IF;
    END;
    PROCEDURE ajouter_contrainte(p_nom VARCHAR2, p_sql VARCHAR2) IS
        n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME=UPPER(p_nom);
        IF n=0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
BEGIN
    ajouter_colonne('AS_BONDECOMMANDE','IDLOT','VARCHAR2(100)');
    ajouter_colonne('AS_BONDECOMMANDE','IDSOUCHE','VARCHAR2(50)');
    ajouter_colonne('AS_BONDECOMMANDE','AGEJOURS','NUMBER(10)');
    ajouter_colonne('AS_BONDECOMMANDE','NBMALEREQUIS','NUMBER(10) DEFAULT 0 NOT NULL');
    ajouter_colonne('AS_BONDECOMMANDE','NBFEMELLEREQUIS','NUMBER(10) DEFAULT 0 NOT NULL');
    ajouter_colonne('AS_BONDECOMMANDE','PAYSDESTINATION','VARCHAR2(120)');
    ajouter_colonne('AS_BONDECOMMANDE','AEROPORTDESTINATION','VARCHAR2(200)');
    ajouter_colonne('AS_BONDECOMMANDE','DATEDEPARTPREVUE','TIMESTAMP');
    ajouter_colonne('AS_BONDECOMMANDE','DATEDEPARTREELLE','TIMESTAMP');
    ajouter_colonne('AS_BONDECOMMANDE','DATEARRIVEEPREVUE','TIMESTAMP');
    ajouter_colonne('AS_BONDECOMMANDE','DATEARRIVEEREELLE','TIMESTAMP');
    ajouter_contrainte('FK_BC_IMPORT_LOT','ALTER TABLE AS_BONDECOMMANDE ADD CONSTRAINT FK_BC_IMPORT_LOT FOREIGN KEY (IDLOT) REFERENCES LOT(ID)');
    ajouter_contrainte('FK_BC_IMPORT_SOUCHE','ALTER TABLE AS_BONDECOMMANDE ADD CONSTRAINT FK_BC_IMPORT_SOUCHE FOREIGN KEY (IDSOUCHE) REFERENCES SOUCHE(ID)');
    ajouter_contrainte('CK_BC_IMPORT_SEXES','ALTER TABLE AS_BONDECOMMANDE ADD CONSTRAINT CK_BC_IMPORT_SEXES CHECK (NBMALEREQUIS >= 0 AND NBFEMELLEREQUIS >= 0)');

    ajouter_colonne('RECEPTIONPOUSSINAEROPORT','IDBC','VARCHAR2(500)');
    ajouter_colonne('RECEPTIONPOUSSINAEROPORT','NBMORTS','NUMBER(10) DEFAULT 0');
    ajouter_colonne('RECEPTIONPOUSSINAEROPORT','NBPERDUS','NUMBER(10) DEFAULT 0');
    ajouter_contrainte('FK_RPA_IMPORT_BC','ALTER TABLE RECEPTIONPOUSSINAEROPORT ADD CONSTRAINT FK_RPA_IMPORT_BC FOREIGN KEY (IDBC) REFERENCES AS_BONDECOMMANDE(ID)');

    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='RECEPTIONPOUSSINPOULAILLER';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE RECEPTIONPOUSSINPOULAILLER (
            ID VARCHAR2(50) NOT NULL, IDRECEPTIONAEROPORT VARCHAR2(50) NOT NULL,
            DATY DATE NOT NULL, HEUREARRIVE VARCHAR2(10) NOT NULL,
            NBMORTS NUMBER(10) DEFAULT 0 NOT NULL, NBVIVANTS NUMBER(10) NOT NULL,
            NBVIVANTSMALE NUMBER(10) DEFAULT 0 NOT NULL, NBVIVANTSFEMELLE NUMBER(10) DEFAULT 0 NOT NULL,
            REMARQUE VARCHAR2(500), ETAT NUMBER(10) DEFAULT 1 NOT NULL,
            CONSTRAINT PK_RECEPTIONPOUSSINPOULAILLER PRIMARY KEY (ID),
            CONSTRAINT FK_RPP_RPA FOREIGN KEY (IDRECEPTIONAEROPORT) REFERENCES RECEPTIONPOUSSINAEROPORT(ID),
            CONSTRAINT UK_RPP_RPA UNIQUE (IDRECEPTIONAEROPORT),
            CONSTRAINT CK_RPP_NBMORTS CHECK (NBMORTS >= 0),
            CONSTRAINT CK_RPP_NBVIVANTS CHECK (NBVIVANTS >= 0)
        )';
    END IF;
    ajouter_colonne('RECEPTIONPOUSSINPOULAILLER','NBVIVANTSMALE','NUMBER(10) DEFAULT 0 NOT NULL');
    ajouter_colonne('RECEPTIONPOUSSINPOULAILLER','NBVIVANTSFEMELLE','NUMBER(10) DEFAULT 0 NOT NULL');
    ajouter_contrainte('CK_RPP_SEXES','ALTER TABLE RECEPTIONPOUSSINPOULAILLER ADD CONSTRAINT CK_RPP_SEXES CHECK (NBVIVANTSMALE >= 0 AND NBVIVANTSFEMELLE >= 0)');

    ajouter_colonne('TRIAGEBATIMENTPARQUET','IDRECEPTIONPOULAILLER','VARCHAR2(50)');
    ajouter_contrainte('FK_TBP_RPP','ALTER TABLE TRIAGEBATIMENTPARQUET ADD CONSTRAINT FK_TBP_RPP FOREIGN KEY (IDRECEPTIONPOULAILLER) REFERENCES RECEPTIONPOUSSINPOULAILLER(ID)');
    ajouter_colonne('TRIAGEBATIMENTPARQUETDETAIL','IDCOMPARTIMENT','VARCHAR2(50)');
    ajouter_colonne('TRIAGEBATIMENTPARQUETDETAIL','SANTE','NUMBER(2)');
    ajouter_colonne('TRIAGEBATIMENTPARQUETDETAIL','REMARQUE','VARCHAR2(500)');
    ajouter_contrainte('FK_TBPD_COMPARTIMENT','ALTER TABLE TRIAGEBATIMENTPARQUETDETAIL ADD CONSTRAINT FK_TBPD_COMPARTIMENT FOREIGN KEY (IDCOMPARTIMENT) REFERENCES BATIMENTDETAIL(ID)');
    ajouter_contrainte('CK_TBPD_SANTE','ALTER TABLE TRIAGEBATIMENTPARQUETDETAIL ADD CONSTRAINT CK_TBPD_SANTE CHECK (SANTE BETWEEN 1 AND 10 OR SANTE IS NULL)');
    ajouter_colonne('BATIMENTDETAIL','ACTIF','NUMBER(1) DEFAULT 1');
    ajouter_contrainte('CK_BATIMENTDETAIL_ACTIF','ALTER TABLE BATIMENTDETAIL ADD CONSTRAINT CK_BATIMENTDETAIL_ACTIF CHECK (ACTIF IN (0,1))');
    EXECUTE IMMEDIATE 'UPDATE BATIMENTDETAIL SET ACTIF=1 WHERE ACTIF IS NULL';
    ajouter_contrainte('UK_TBP_RPP','ALTER TABLE TRIAGEBATIMENTPARQUET ADD CONSTRAINT UK_TBP_RPP UNIQUE (IDRECEPTIONPOULAILLER)');
END;
/

DECLARE n NUMBER; BEGIN
    SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME='SEQ_RECEPTIONPOUSSINPOULAILLER';
    IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RECEPTIONPOUSSINPOULAILLER START WITH 1 INCREMENT BY 1 NOCYCLE'; END IF;
END;
/

CREATE OR REPLACE FUNCTION GETSEQRECEPTIONPOULAILLER RETURN NUMBER IS
    retour NUMBER;
BEGIN
    SELECT SEQ_RECEPTIONPOUSSINPOULAILLER.NEXTVAL INTO retour FROM DUAL;
    RETURN retour;
END;
