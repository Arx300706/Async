CREATE OR REPLACE VIEW AS_BONDECOMMANDE_POUSSIN_LIB AS
SELECT b.ID, b.DATY, b.ETAT, b.REFERENCE, b.REMARQUE, b.FOURNISSEUR, f.NOM AS FOURNISSEURLIB,
       NVL(b.IDLOT, r.IDLOT) AS IDLOT, l.NOMLOT AS IDLOTLIB, b.IDSOUCHE, s.VAL AS IDSOUCHELIB,
       b.AGEJOURS, b.NBMALEREQUIS, b.NBFEMELLEREQUIS,
       CASE WHEN b.AGEJOURS IS NULL THEN NULL
            WHEN b.AGEJOURS < 7 THEN b.AGEJOURS || ' jour(s)'
            WHEN MOD(b.AGEJOURS,7)=0 THEN b.AGEJOURS || ' jours (' || TRUNC(b.AGEJOURS/7) || ' semaine(s))'
            ELSE b.AGEJOURS || ' jours (' || TRUNC(b.AGEJOURS/7) || ' semaine(s) + ' || MOD(b.AGEJOURS,7) || ' jour(s))' END AS AGELIB,
       b.IDMAGASIN, m.VAL AS IDMAGASINLIB, b.PAYSDESTINATION, b.AEROPORTDESTINATION,
       b.DATEDEPARTPREVUE, b.DATEDEPARTREELLE, b.DATEARRIVEEPREVUE, b.DATEARRIVEEREELLE,
       NVL(q.QUANTITECOMMANDEE,0) AS QUANTITECOMMANDEE, NVL(q.PU,0) AS PU, NVL(q.MONTANT,0) AS MONTANT,
       r.ID AS IDRECEPTIONAEROPORT, r.NBMORTS AS NBMORTSAEROPORT, r.NBPERDUS AS NBPERDUSAEROPORT, r.QTERECUS AS NBVIVANTSAEROPORT,
       NVL(rd.NBVIVANTSMALE,0) AS NBVIVANTSMALEAEROPORT, NVL(rd.NBVIVANTSFEMELLE,0) AS NBVIVANTSFEMELLEAEROPORT,
       p.ID AS IDRECEPTIONPOULAILLER, p.NBMORTS AS NBMORTSPOULAILLER, p.NBVIVANTS AS NBVIVANTSPOULAILLER,
       p.NBVIVANTSMALE AS NBVIVANTSMALEPOULAILLER, p.NBVIVANTSFEMELLE AS NBVIVANTSFEMELLEPOULAILLER,
       t.ID AS IDREMPLISSAGE,
       CASE WHEN b.ETAT=0 THEN 'Annule'
            WHEN b.ETAT<11 THEN 'Brouillon'
            WHEN t.ETAT=11 THEN 'Termine'
            WHEN p.ETAT=11 THEN 'Receptionne au poulailler'
            WHEN r.ETAT=11 THEN 'Arrive a l''aeroport'
            WHEN b.DATEDEPARTREELLE IS NOT NULL THEN 'Expedie'
            ELSE 'Valide' END AS STATUT
FROM AS_BONDECOMMANDE b
LEFT JOIN FOURNISSEUR f ON f.ID=b.FOURNISSEUR
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDBC, SUM(QUANTITE) QUANTITECOMMANDEE, MAX(PU) PU, SUM(NVL(MONTANT,QUANTITE*PU)) MONTANT FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID
LEFT JOIN RECEPTIONPOUSSINAEROPORT r ON r.IDBC=b.ID
LEFT JOIN (SELECT IDMERE,
                  SUM(CASE WHEN IDSEXE='1' THEN QTE ELSE 0 END) NBVIVANTSMALE,
                  SUM(CASE WHEN IDSEXE='0' THEN QTE ELSE 0 END) NBVIVANTSFEMELLE
           FROM RECEPTIONPOUSSINAEROPORTDETAIL GROUP BY IDMERE) rd ON rd.IDMERE=r.ID
LEFT JOIN LOT l ON l.ID=NVL(b.IDLOT, r.IDLOT)
LEFT JOIN RECEPTIONPOUSSINPOULAILLER p ON p.IDRECEPTIONAEROPORT=r.ID
LEFT JOIN TRIAGEBATIMENTPARQUET t ON t.IDRECEPTIONPOULAILLER=p.ID
WHERE b.IDSOUCHE IS NOT NULL;
/

CREATE OR REPLACE VIEW RPA_IMPORT_LIB AS
SELECT r.*, b.ID AS NUMEROBON, b.FOURNISSEUR, f.NOM AS FOURNISSEURLIB,
       b.IDSOUCHE, s.VAL AS IDSOUCHELIB, b.AGEJOURS, b.NBMALEREQUIS, b.NBFEMELLEREQUIS,
       b.PAYSDESTINATION, b.AEROPORTDESTINATION,
       b.DATEDEPARTPREVUE, b.DATEDEPARTREELLE, b.DATEARRIVEEPREVUE,
       q.QUANTITECOMMANDEE, NVL(rd.NBVIVANTSMALE,0) AS NBVIVANTSMALE,
       NVL(rd.NBVIVANTSFEMELLE,0) AS NBVIVANTSFEMELLE,
       (r.QTERECUS+r.NBMORTS+r.NBPERDUS-q.QUANTITECOMMANDEE) AS ECART,
       CASE WHEN r.QTERECUS+r.NBMORTS+r.NBPERDUS=q.QUANTITECOMMANDEE THEN 'Conforme' ELSE 'Non conforme' END AS CONFORMITE,
       CASE r.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END AS ETATLIB
FROM RECEPTIONPOUSSINAEROPORT r
JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN FOURNISSEUR f ON f.ID=b.FOURNISSEUR
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN (SELECT IDBC,SUM(QUANTITE) QUANTITECOMMANDEE FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID
LEFT JOIN (SELECT IDMERE,
                  SUM(CASE WHEN IDSEXE='1' THEN QTE ELSE 0 END) NBVIVANTSMALE,
                  SUM(CASE WHEN IDSEXE='0' THEN QTE ELSE 0 END) NBVIVANTSFEMELLE
           FROM RECEPTIONPOUSSINAEROPORTDETAIL GROUP BY IDMERE) rd ON rd.IDMERE=r.ID;
/

CREATE OR REPLACE VIEW RPP_IMPORT_LIB AS
SELECT p.*, r.IDLOT, r.IDBC, b.ID AS NUMEROBON, b.IDSOUCHE, s.VAL AS IDSOUCHELIB,
       b.AGEJOURS, b.NBMALEREQUIS, b.NBFEMELLEREQUIS,
       b.IDMAGASIN, m.VAL AS IDMAGASINLIB, q.QUANTITECOMMANDEE,
       r.NBMORTS AS NBMORTSAEROPORT, r.NBPERDUS AS NBPERDUSAEROPORT, r.QTERECUS AS NBVIVANTSAEROPORT,
       NVL(rd.NBVIVANTSMALE,0) AS NBVIVANTSMALEAEROPORT,
       NVL(rd.NBVIVANTSFEMELLE,0) AS NBVIVANTSFEMELLEAEROPORT,
       CASE p.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END AS ETATLIB
FROM RECEPTIONPOUSSINPOULAILLER p
JOIN RECEPTIONPOUSSINAEROPORT r ON r.ID=p.IDRECEPTIONAEROPORT
JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDBC,SUM(QUANTITE) QUANTITECOMMANDEE FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID
LEFT JOIN (SELECT IDMERE,
                  SUM(CASE WHEN IDSEXE='1' THEN QTE ELSE 0 END) NBVIVANTSMALE,
                  SUM(CASE WHEN IDSEXE='0' THEN QTE ELSE 0 END) NBVIVANTSFEMELLE
           FROM RECEPTIONPOUSSINAEROPORTDETAIL GROUP BY IDMERE) rd ON rd.IDMERE=r.ID;
/

CREATE OR REPLACE VIEW TRIAGEBPARQ_IMPORT_LIB AS
SELECT t.*, p.IDRECEPTIONAEROPORT, r.IDBC, b.ID AS NUMEROBON, b.IDSOUCHE, s.VAL AS IDSOUCHELIB,
       b.AGEJOURS, b.IDMAGASIN, m.VAL AS IDMAGASINLIB, p.NBVIVANTS,
       NVL(a.QTEAFFECTEE,0) AS QTEAFFECTEE, p.NBVIVANTS-NVL(a.QTEAFFECTEE,0) AS RESTEAFFECTER,
       CASE t.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END AS ETATLIB
FROM TRIAGEBATIMENTPARQUET t
JOIN RECEPTIONPOUSSINPOULAILLER p ON p.ID=t.IDRECEPTIONPOULAILLER
JOIN RECEPTIONPOUSSINAEROPORT r ON r.ID=p.IDRECEPTIONAEROPORT
JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDMERE,SUM(QTE) QTEAFFECTEE FROM TRIAGEBATIMENTPARQUETDETAIL GROUP BY IDMERE) a ON a.IDMERE=t.ID;
/

CREATE OR REPLACE VIEW TRIAGEBPARQDET_IMPORTLIB AS
SELECT d.ID, d.IDMERE, d.IDCOMPARTIMENT, d.IDSEXE, d.IDQUALITE, d.QTE, d.SANTE, d.REMARQUE,
       b.IDMERE AS IDBATIMENT, b.IDPARQUET, ba.NOMBATIMENT AS IDBATIMENTLIB,
       pa.VAL AS IDPARQUETLIB, sx.VAL AS IDSEXELIB,
       b.CAPACITE AS CAPACITEMAX,
       NVL(o.OCCUPE,0) AS OCCUPE,
       b.CAPACITE-NVL(o.OCCUPE,0) AS RESTECAPACITE
FROM TRIAGEBATIMENTPARQUETDETAIL d
JOIN BATIMENTDETAIL b ON b.ID=d.IDCOMPARTIMENT
JOIN BATIMENT ba ON ba.ID=b.IDMERE
JOIN PARQUET pa ON pa.ID=b.IDPARQUET
LEFT JOIN SEXE sx ON sx.ID=d.IDSEXE
LEFT JOIN (SELECT d2.IDCOMPARTIMENT,SUM(d2.QTE) OCCUPE FROM TRIAGEBATIMENTPARQUETDETAIL d2 JOIN TRIAGEBATIMENTPARQUET t2 ON t2.ID=d2.IDMERE WHERE t2.ETAT IN (1,11) GROUP BY d2.IDCOMPARTIMENT) o ON o.IDCOMPARTIMENT=d.IDCOMPARTIMENT;
/

CREATE OR REPLACE VIEW BATDETAIL_COMPARTIMENT_LIB AS
SELECT b.ID, b.IDMERE, b.IDPARQUET, b.CAPACITE, b.IDSEXE, b.ACTIF,
       ba.NOMBATIMENT AS IDBATIMENTLIB, pa.VAL AS IDPARQUETLIB,
       ba.NOMBATIMENT || ' / ' || pa.VAL AS LIBELLE, sx.VAL AS IDSEXELIB,
       NVL(o.OCCUPE,0) AS OCCUPE, b.CAPACITE-NVL(o.OCCUPE,0) AS RESTECAPACITE
FROM BATIMENTDETAIL b
JOIN BATIMENT ba ON ba.ID=b.IDMERE
JOIN PARQUET pa ON pa.ID=b.IDPARQUET
LEFT JOIN SEXE sx ON sx.ID=b.IDSEXE
LEFT JOIN (SELECT d.IDCOMPARTIMENT,SUM(d.QTE) OCCUPE FROM TRIAGEBATIMENTPARQUETDETAIL d JOIN TRIAGEBATIMENTPARQUET t ON t.ID=d.IDMERE WHERE t.ETAT IN (1,11) GROUP BY d.IDCOMPARTIMENT) o ON o.IDCOMPARTIMENT=b.ID;
/

CREATE OR REPLACE VIEW V_TRACE_IMPORT_POUSSIN AS
SELECT b.ID AS IDBON, b.REFERENCE AS NUMEROBON, b.DATY AS DATECOMMANDE, f.NOM AS FOURNISSEUR,
       l.NOMLOT, s.VAL AS RACE, b.AGEJOURS, b.IDMAGASIN AS IDPOULAILLER, m.VAL AS POULAILLER,
       b.PAYSDESTINATION, b.AEROPORTDESTINATION, b.NBMALEREQUIS, b.NBFEMELLEREQUIS,
       q.QUANTITECOMMANDEE, q.MONTANT,
       b.DATEDEPARTPREVUE, b.DATEDEPARTREELLE, b.DATEARRIVEEPREVUE, b.DATEARRIVEEREELLE,
       r.ID AS IDRECEPTIONAEROPORT, r.DATY AS DATER1, r.HEUREARRIVE AS HEURER1, r.NBMORTS AS MORTSR1, r.NBPERDUS AS PERDUSR1, r.QTERECUS AS VIVANTSR1, r.ETAT AS ETATR1,
       NVL(rd.NBVIVANTSMALE,0) AS VIVANTSMALER1, NVL(rd.NBVIVANTSFEMELLE,0) AS VIVANTSFEMELLER1,
       p.ID AS IDRECEPTIONPOULAILLER, p.DATY AS DATER2, p.HEUREARRIVE AS HEURER2, p.NBMORTS AS MORTSR2, p.NBVIVANTS AS VIVANTSR2,
       p.NBVIVANTSMALE AS VIVANTSMALER2, p.NBVIVANTSFEMELLE AS VIVANTSFEMELLER2, p.ETAT AS ETATR2,
       t.ID AS IDREMPLISSAGE, t.ETAT AS ETATREMPLISSAGE,
       d.ID AS IDLIGNE, d.QTE AS QTEAFFECTEE, d.SANTE, d.REMARQUE AS REMARQUELIGNE,
       ba.NOMBATIMENT AS BATIMENT, pa.VAL AS COMPARTIMENT, sx.VAL AS SEXE, bd.CAPACITE AS CAPACITEMAX
FROM AS_BONDECOMMANDE b
LEFT JOIN FOURNISSEUR f ON f.ID=b.FOURNISSEUR
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDBC,SUM(QUANTITE) QUANTITECOMMANDEE,SUM(NVL(MONTANT,QUANTITE*PU)) MONTANT FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID
LEFT JOIN RECEPTIONPOUSSINAEROPORT r ON r.IDBC=b.ID
LEFT JOIN (SELECT IDMERE,
                  SUM(CASE WHEN IDSEXE='1' THEN QTE ELSE 0 END) NBVIVANTSMALE,
                  SUM(CASE WHEN IDSEXE='0' THEN QTE ELSE 0 END) NBVIVANTSFEMELLE
           FROM RECEPTIONPOUSSINAEROPORTDETAIL GROUP BY IDMERE) rd ON rd.IDMERE=r.ID
LEFT JOIN LOT l ON l.ID=NVL(b.IDLOT, r.IDLOT)
LEFT JOIN RECEPTIONPOUSSINPOULAILLER p ON p.IDRECEPTIONAEROPORT=r.ID
LEFT JOIN TRIAGEBATIMENTPARQUET t ON t.IDRECEPTIONPOULAILLER=p.ID
LEFT JOIN TRIAGEBATIMENTPARQUETDETAIL d ON d.IDMERE=t.ID
LEFT JOIN BATIMENTDETAIL bd ON bd.ID=d.IDCOMPARTIMENT
LEFT JOIN BATIMENT ba ON ba.ID=bd.IDMERE
LEFT JOIN PARQUET pa ON pa.ID=bd.IDPARQUET
LEFT JOIN SEXE sx ON sx.ID=d.IDSEXE
WHERE b.IDSOUCHE IS NOT NULL;
/

