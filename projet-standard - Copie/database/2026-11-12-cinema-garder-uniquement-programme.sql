-- =====================================================================
-- Module cinema : ne garder QUE le programme de diffusion du 16/11/2026 au 30/11/2026
--   Films   : Les Gardiens du Baobab, Nuit sur Analamanga, Le Petit Lemurien
--   Salles  : Salle A, Salle B, Salle C
--   Seances : celles de ces films, dans ces salles, du 16/11 au 30/11/2026 (visees)
-- Supprime tout le reste du module cinema : reservations / places vendues
-- (avec leurs paiements et ecritures comptables), autres seances, autres films,
-- leurs contrats / receptions / factures, autres salles, distributeur DEMO.
-- A executer avec ARBIOCHEMSTANDARD. IRREVERSIBLE.
-- =====================================================================
SET DEFINE OFF;
SET SERVEROUTPUT ON;

-- Ensembles de travail (supprimes en fin de script)
CREATE OR REPLACE VIEW TMP_CINE_FILMS AS
    SELECT ID FROM AS_INGREDIENTS WHERE CATEGORIEINGREDIENT = 'CATFILM'
       AND (LIBELLE IN ('Les Gardiens du Baobab', 'Nuit sur Analamanga') OR LIBELLE LIKE 'Le Petit L_murien');

CREATE OR REPLACE VIEW TMP_CINE_SALLES AS
    SELECT ID FROM MAGASIN2 WHERE IDTYPEMAGASIN = 'TYPMGSALLE' AND VAL IN ('Salle A', 'Salle B', 'Salle C');

CREATE OR REPLACE VIEW TMP_CINE_SEANCES AS
    SELECT ID FROM PLANNING WHERE IDTYPEMAINTENANCE = 'TMSEANCE' AND ETAT = 11
       AND REFOBJET IN (SELECT ID FROM TMP_CINE_FILMS) AND IDMACHINE IN (SELECT ID FROM TMP_CINE_SALLES)
       AND DATEDEBUT BETWEEN DATE '2026-11-16' AND DATE '2026-11-30';

CREATE OR REPLACE VIEW TMP_CINE_RESA AS
    SELECT DISTINCT rd.IDMERE AS ID FROM RESERVATIONDETAILS rd
      JOIN PLANNING p ON p.ID = rd.IDPRODUIT AND p.IDTYPEMAINTENANCE = 'TMSEANCE';

CREATE OR REPLACE VIEW TMP_CINE_ANCIENS_BC AS
    SELECT bc.ID FROM AS_BONDECOMMANDE bc
     WHERE EXISTS (SELECT 1 FROM AS_BONDECOMMANDE_FILLE f JOIN AS_INGREDIENTS i ON i.ID = f.PRODUIT
                    WHERE f.IDBC = bc.ID AND i.CATEGORIEINGREDIENT = 'CATFILM' AND i.ID NOT IN (SELECT ID FROM TMP_CINE_FILMS));

DECLARE
    TYPE t_ids IS TABLE OF VARCHAR2(100);
    v_resa t_ids;
    v_bc   t_ids;
    PROCEDURE info(p VARCHAR2, n NUMBER) IS BEGIN DBMS_OUTPUT.PUT_LINE(RPAD(p, 45) || n); END;
BEGIN
    -- Les ensembles sont memorises AVANT les suppressions (ils dependent des lignes filles)
    SELECT ID BULK COLLECT INTO v_resa FROM TMP_CINE_RESA;
    SELECT ID BULK COLLECT INTO v_bc FROM TMP_CINE_ANCIENS_BC;
    -- 1. Toutes les reservations de cinema (places vendues / reservees) et leurs paiements
    DELETE FROM COMPTA_SOUS_ECRITURE WHERE IDMERE IN (
        SELECT ID FROM COMPTA_ECRITURE WHERE IDOBJET IN (SELECT ID FROM MOUVEMENTCAISSE WHERE IDOP IN (SELECT ID FROM TMP_CINE_RESA))
                                          OR ORIGINE IN (SELECT ID FROM MOUVEMENTCAISSE WHERE IDOP IN (SELECT ID FROM TMP_CINE_RESA)));
    info('Sous-ecritures (paiements billets)', SQL%ROWCOUNT);
    DELETE FROM COMPTA_ECRITURE WHERE IDOBJET IN (SELECT ID FROM MOUVEMENTCAISSE WHERE IDOP IN (SELECT ID FROM TMP_CINE_RESA))
                                   OR ORIGINE IN (SELECT ID FROM MOUVEMENTCAISSE WHERE IDOP IN (SELECT ID FROM TMP_CINE_RESA));
    info('Ecritures (paiements billets)', SQL%ROWCOUNT);
    DELETE FROM MOUVEMENTCAISSE WHERE IDOP IN (SELECT ID FROM TMP_CINE_RESA);
    info('Mouvements de caisse (paiements billets)', SQL%ROWCOUNT);
    DELETE FROM RESERVATIONDETAILS WHERE IDMERE IN (SELECT ID FROM TMP_CINE_RESA);
    info('Places reservees / vendues', SQL%ROWCOUNT);
    FORALL i IN 1 .. v_resa.COUNT DELETE FROM RESERVATION WHERE ID = v_resa(i);
    info('Reservations', SQL%ROWCOUNT);

    -- 2. Seances hors programme
    DELETE FROM PLANNING WHERE IDTYPEMAINTENANCE = 'TMSEANCE' AND ID NOT IN (SELECT ID FROM TMP_CINE_SEANCES);
    info('Seances hors programme', SQL%ROWCOUNT);

    -- 3. Contrats des autres films : factures, receptions, contrats
    DELETE FROM COMPTA_SOUS_ECRITURE WHERE IDMERE IN (SELECT ID FROM COMPTA_ECRITURE WHERE IDOBJET IN
        (SELECT ID FROM FACTUREFOURNISSEUR WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC)));
    DELETE FROM COMPTA_ECRITURE WHERE IDOBJET IN (SELECT ID FROM FACTUREFOURNISSEUR WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC));
    UPDATE AS_BONDELIVRAISON SET IDFACTUREFOURNISSEUR = NULL WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC);
    DELETE FROM FACTUREFOURNISSEURFILLE WHERE IDFACTUREFOURNISSEUR IN (SELECT ID FROM FACTUREFOURNISSEUR WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC));
    DELETE FROM FACTUREFOURNISSEUR WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC);
    info('Factures fournisseur (anciens films)', SQL%ROWCOUNT);
    DELETE FROM AS_BONDELIVRAISON_FILLE WHERE NUMBL IN (SELECT ID FROM AS_BONDELIVRAISON WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC));
    DELETE FROM AS_BONDELIVRAISON WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC);
    info('Receptions (anciens films)', SQL%ROWCOUNT);
    DELETE FROM AS_BONDECOMMANDE_FILLE WHERE IDBC IN (SELECT ID FROM TMP_CINE_ANCIENS_BC);
    FORALL i IN 1 .. v_bc.COUNT DELETE FROM AS_BONDECOMMANDE WHERE ID = v_bc(i);
    info('Contrats (anciens films)', SQL%ROWCOUNT);

    -- 4. Autres films, autres salles, distributeur DEMO
    DELETE FROM AS_INGREDIENTS WHERE CATEGORIEINGREDIENT = 'CATFILM' AND ID NOT IN (SELECT ID FROM TMP_CINE_FILMS);
    info('Films supprimes', SQL%ROWCOUNT);
    DELETE FROM MAGASIN2 WHERE IDTYPEMAGASIN = 'TYPMGSALLE' AND ID NOT IN (SELECT ID FROM TMP_CINE_SALLES);
    info('Salles supprimees', SQL%ROWCOUNT);
    DELETE FROM FOURNISSEUR WHERE IDTYPEFOURNISSEUR = 'TPFCINE' AND NOM LIKE 'DEMO%'
       AND ID NOT IN (SELECT FOURNISSEUR FROM AS_BONDECOMMANDE WHERE FOURNISSEUR IS NOT NULL);
    info('Distributeur DEMO supprime', SQL%ROWCOUNT);

    -- Films / salles conserves : actifs
    UPDATE AS_INGREDIENTS SET ACTIF = 1 WHERE ID IN (SELECT ID FROM TMP_CINE_FILMS);
    UPDATE MAGASIN2 SET ACTIF = 1 WHERE ID IN (SELECT ID FROM TMP_CINE_SALLES);

    COMMIT;
END;
/

DROP VIEW TMP_CINE_ANCIENS_BC;
DROP VIEW TMP_CINE_RESA;
DROP VIEW TMP_CINE_SEANCES;
DROP VIEW TMP_CINE_SALLES;
DROP VIEW TMP_CINE_FILMS;

-- Verification
SELECT 'Films' AS QUOI, COUNT(*) AS NB FROM AS_INGREDIENTS WHERE CATEGORIEINGREDIENT = 'CATFILM'
UNION ALL SELECT 'Salles', COUNT(*) FROM MAGASIN2 WHERE IDTYPEMAGASIN = 'TYPMGSALLE'
UNION ALL SELECT 'Seances', COUNT(*) FROM PLANNING WHERE IDTYPEMAINTENANCE = 'TMSEANCE'
UNION ALL SELECT 'Places vendues / reservees', COUNT(*) FROM V_SEANCE_PLACES_OCCUPEES
UNION ALL SELECT 'Contrats de films', COUNT(*) FROM V_CONTRAT_FILM;
