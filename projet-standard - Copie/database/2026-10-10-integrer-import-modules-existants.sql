DECLARE
    n NUMBER;
    nullable_col VARCHAR2(1);
    PROCEDURE ajouter_colonne(p_table VARCHAR2, p_colonne VARCHAR2, p_definition VARCHAR2) IS
        c NUMBER;
    BEGIN
        SELECT COUNT(*) INTO c FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME=UPPER(p_table) AND COLUMN_NAME=UPPER(p_colonne);
        IF c=0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE '||p_table||' ADD ('||p_colonne||' '||p_definition||')';
        END IF;
    END;
    PROCEDURE ajouter_contrainte(p_nom VARCHAR2, p_sql VARCHAR2) IS
        c NUMBER;
    BEGIN
        SELECT COUNT(*) INTO c FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME=UPPER(p_nom);
        IF c=0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
BEGIN
    SELECT NULLABLE INTO nullable_col FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME='RECEPTIONPOUSSINAEROPORT' AND COLUMN_NAME='IDLOT';
    IF nullable_col='N' THEN EXECUTE IMMEDIATE 'ALTER TABLE RECEPTIONPOUSSINAEROPORT MODIFY (IDLOT NULL)'; END IF;
    SELECT NULLABLE INTO nullable_col FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME='TRANSFERTPOULET' AND COLUMN_NAME='IDLOT';
    IF nullable_col='N' THEN EXECUTE IMMEDIATE 'ALTER TABLE TRANSFERTPOULET MODIFY (IDLOT NULL)'; END IF;

    ajouter_colonne('TRANSFERTPOULET','IDRECEPTIONAEROPORT','VARCHAR2(50)');
    ajouter_colonne('TRANSFERTPOULET','HEUREARRIVE','VARCHAR2(10)');
    ajouter_colonne('TRANSFERTPOULET','NBMORTS','NUMBER(10) DEFAULT 0');
    ajouter_colonne('TRANSFERTPOULET','NBPERDUS','NUMBER(10) DEFAULT 0');
    ajouter_colonne('TRANSFERTPOULET','NBVIVANTS','NUMBER(10) DEFAULT 0');
    ajouter_colonne('TRANSFERTPOULET','IDCONTROLEUR','VARCHAR2(50)');
    ajouter_colonne('TRANSFERTPOULET','IDCHAUFFEUR','VARCHAR2(50)');
    ajouter_colonne('TRANSFERTPOULET','IDVEHICULE','VARCHAR2(50)');
    ajouter_contrainte('FK_TRP_IMPORT_RPA','ALTER TABLE TRANSFERTPOULET ADD CONSTRAINT FK_TRP_IMPORT_RPA FOREIGN KEY (IDRECEPTIONAEROPORT) REFERENCES RECEPTIONPOUSSINAEROPORT(ID)');
    ajouter_contrainte('FK_TRP_IMPORT_CTRL','ALTER TABLE TRANSFERTPOULET ADD CONSTRAINT FK_TRP_IMPORT_CTRL FOREIGN KEY (IDCONTROLEUR) REFERENCES LOG_PERSONNEL(ID)');
    ajouter_contrainte('FK_TRP_IMPORT_CHF','ALTER TABLE TRANSFERTPOULET ADD CONSTRAINT FK_TRP_IMPORT_CHF FOREIGN KEY (IDCHAUFFEUR) REFERENCES LOG_PERSONNEL(ID)');
    ajouter_contrainte('FK_TRP_IMPORT_VEH','ALTER TABLE TRANSFERTPOULET ADD CONSTRAINT FK_TRP_IMPORT_VEH FOREIGN KEY (IDVEHICULE) REFERENCES VEHICULE(ID)');
    ajouter_contrainte('CK_TRP_IMPORT_QTE','ALTER TABLE TRANSFERTPOULET ADD CONSTRAINT CK_TRP_IMPORT_QTE CHECK (NBMORTS>=0 AND NBPERDUS>=0 AND NBVIVANTS>=0)');
    ajouter_contrainte('UK_TRP_IMPORT_RPA','ALTER TABLE TRANSFERTPOULET ADD CONSTRAINT UK_TRP_IMPORT_RPA UNIQUE (IDRECEPTIONAEROPORT)');

    ajouter_colonne('TRIAGEBATIMENTPARQUET','IDTRANSFERTPOULET','VARCHAR2(50)');
    ajouter_contrainte('FK_TBP_IMPORT_TRP','ALTER TABLE TRIAGEBATIMENTPARQUET ADD CONSTRAINT FK_TBP_IMPORT_TRP FOREIGN KEY (IDTRANSFERTPOULET) REFERENCES TRANSFERTPOULET(ID)');
    ajouter_contrainte('UK_TBP_IMPORT_TRP','ALTER TABLE TRIAGEBATIMENTPARQUET ADD CONSTRAINT UK_TBP_IMPORT_TRP UNIQUE (IDTRANSFERTPOULET)');
END;
/

CREATE OR REPLACE VIEW AS_BONDECOMMANDE_POUSSIN_LIB AS
SELECT b.ID,b.DATY,b.ETAT,b.REFERENCE,b.REMARQUE,b.FOURNISSEUR,f.NOM FOURNISSEURLIB,
       NVL(t.IDLOT,NVL(r.IDLOT,b.IDLOT)) IDLOT,l.NOMLOT IDLOTLIB,b.IDSOUCHE,s.VAL IDSOUCHELIB,
       b.AGEJOURS,b.NBMALEREQUIS,b.NBFEMELLEREQUIS,
       CASE WHEN b.AGEJOURS IS NULL THEN NULL
            WHEN b.AGEJOURS<7 THEN b.AGEJOURS||' jour(s)'
            WHEN MOD(b.AGEJOURS,7)=0 THEN b.AGEJOURS||' jours ('||TRUNC(b.AGEJOURS/7)||' semaine(s))'
            ELSE b.AGEJOURS||' jours ('||TRUNC(b.AGEJOURS/7)||' semaine(s) + '||MOD(b.AGEJOURS,7)||' jour(s))' END AGELIB,
       b.IDMAGASIN,m.VAL IDMAGASINLIB,b.PAYSDESTINATION,b.AEROPORTDESTINATION,
       b.DATEDEPARTPREVUE,b.DATEDEPARTREELLE,b.DATEARRIVEEPREVUE,b.DATEARRIVEEREELLE,
       NVL(q.QUANTITECOMMANDEE,0) QUANTITECOMMANDEE,NVL(q.PU,0) PU,NVL(q.MONTANT,0) MONTANT,
       r.ID IDRECEPTIONAEROPORT,NVL(r.NBMORTS,0) NBMORTSAEROPORT,NVL(r.NBPERDUS,0) NBPERDUSAEROPORT,NVL(r.QTERECUS,0) NBVIVANTSAEROPORT,
       tr.ID IDTRANSFERTPOULET,NVL(tr.NBMORTS,0) NBMORTSTRAJET,NVL(tr.NBPERDUS,0) NBPERDUSTRAJET,NVL(tr.NBVIVANTS,0) NBVIVANTSTRANSFERT,
       t.ID IDTRIAGE,NVL(t.DISPOMALE,0) NBVIVANTSMALETRIAGE,NVL(t.DISPOFEMELLE,0) NBVIVANTSFEMELLETRIAGE,
       CASE WHEN b.ETAT=0 THEN 'Annule'
            WHEN b.ETAT<11 THEN 'Brouillon'
            WHEN t.ETAT=11 THEN 'Termine'
            WHEN tr.ETAT=11 THEN 'Arrive au poulailler'
            WHEN r.ETAT=11 THEN 'Recu a l''aeroport'
            WHEN b.DATEDEPARTREELLE IS NOT NULL THEN 'Expedie'
            ELSE 'Valide' END STATUT
FROM AS_BONDECOMMANDE b
LEFT JOIN FOURNISSEUR f ON f.ID=b.FOURNISSEUR
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDBC,SUM(QUANTITE) QUANTITECOMMANDEE,MAX(PU) PU,SUM(NVL(MONTANT,QUANTITE*PU)) MONTANT FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID
LEFT JOIN RECEPTIONPOUSSINAEROPORT r ON r.IDBC=b.ID
LEFT JOIN TRANSFERTPOULET tr ON tr.IDRECEPTIONAEROPORT=r.ID
LEFT JOIN TRIAGEBATIMENTPARQUET t ON t.IDTRANSFERTPOULET=tr.ID
LEFT JOIN LOT l ON l.ID=NVL(t.IDLOT,NVL(r.IDLOT,b.IDLOT))
WHERE b.IDSOUCHE IS NOT NULL;
/

CREATE OR REPLACE VIEW RPA_IMPORT_LIB AS
SELECT r.*,b.ID NUMEROBON,b.FOURNISSEUR,f.NOM FOURNISSEURLIB,b.IDSOUCHE,s.VAL IDSOUCHELIB,
       b.AGEJOURS,b.NBMALEREQUIS,b.NBFEMELLEREQUIS,b.PAYSDESTINATION,b.AEROPORTDESTINATION,
       b.DATEDEPARTPREVUE,b.DATEDEPARTREELLE,b.DATEARRIVEEPREVUE,q.QUANTITECOMMANDEE,
       0 NBVIVANTSMALE,0 NBVIVANTSFEMELLE,
       (NVL(r.QTERECUS,0)+NVL(r.NBMORTS,0)+NVL(r.NBPERDUS,0)-q.QUANTITECOMMANDEE) ECART,
       CASE WHEN NVL(r.QTERECUS,0)+NVL(r.NBMORTS,0)+NVL(r.NBPERDUS,0)=q.QUANTITECOMMANDEE THEN 'Conforme' ELSE 'Non conforme' END CONFORMITE,
       CASE r.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END ETATLIB
FROM RECEPTIONPOUSSINAEROPORT r
JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN FOURNISSEUR f ON f.ID=b.FOURNISSEUR
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN (SELECT IDBC,SUM(QUANTITE) QUANTITECOMMANDEE FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID;
/

CREATE OR REPLACE VIEW TRANSFERTPOULET_LIB AS
SELECT t.*,l.NOMLOT IDLOTLIB,NVL(s.VAL,sl.VAL) IDSOUCHELIB,
       CASE t.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END ETATLIB,
       b.ID NUMEROBON,f.NOM FOURNISSEURLIB,b.IDMAGASIN,m.VAL IDMAGASINLIB,b.AGEJOURS,
       r.DATY DATERECEPTIONAEROPORT,r.HEUREARRIVE HEURERECEPTIONAEROPORT,
       NVL(r.NBMORTS,0) NBMORTSAEROPORT,NVL(r.NBPERDUS,0) NBPERDUSAEROPORT,NVL(r.QTERECUS,0) NBVIVANTSAEROPORT,
       NVL(q.QUANTITECOMMANDEE,0) QUANTITECOMMANDEE
FROM TRANSFERTPOULET t
LEFT JOIN RECEPTIONPOUSSINAEROPORT r ON r.ID=t.IDRECEPTIONAEROPORT
LEFT JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN FOURNISSEUR f ON f.ID=b.FOURNISSEUR
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN LOT l ON l.ID=NVL(t.IDLOT,r.IDLOT)
LEFT JOIN SOUCHE sl ON sl.ID=l.IDSOUCHE
LEFT JOIN (SELECT IDBC,SUM(QUANTITE) QUANTITECOMMANDEE FROM AS_BONDECOMMANDE_FILLE GROUP BY IDBC) q ON q.IDBC=b.ID;
/

CREATE OR REPLACE VIEW TRIAGEBATIMENTPARQUET_LIB AS
SELECT t.*,l.NOMLOT IDLOTLIB,l.IDSOUCHE,s.VAL IDSOUCHELIB,
       CASE t.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END ETATLIB,
       TO_CHAR(NVL(t.DISPOFEMELLE,0)-NVL(a.FEMELLES,0)) ECARTFEMELLE,
       TO_CHAR(NVL(t.DISPOMALE,0)-NVL(a.MALES,0)) ECARTMALE,
       b.ID NUMEROBON,m.VAL IDMAGASINLIB,NVL(tr.NBVIVANTS,NVL(t.DISPOMALE,0)+NVL(t.DISPOFEMELLE,0)) NBVIVANTS,
       NVL(tr.NBMORTS,0) NBMORTSTRAJET,NVL(tr.NBPERDUS,0) NBPERDUSTRAJET,
       NVL(a.TOTAL,0) QTEAFFECTEE,NVL(tr.NBVIVANTS,NVL(t.DISPOMALE,0)+NVL(t.DISPOFEMELLE,0))-NVL(a.TOTAL,0) RESTEAFFECTER
FROM TRIAGEBATIMENTPARQUET t
LEFT JOIN LOT l ON l.ID=t.IDLOT
LEFT JOIN SOUCHE s ON s.ID=l.IDSOUCHE
LEFT JOIN TRANSFERTPOULET tr ON tr.ID=t.IDTRANSFERTPOULET
LEFT JOIN RECEPTIONPOUSSINAEROPORT r ON r.ID=tr.IDRECEPTIONAEROPORT
LEFT JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDMERE,SUM(QTE) TOTAL,SUM(CASE WHEN IDSEXE='1' THEN QTE ELSE 0 END) MALES,SUM(CASE WHEN IDSEXE='0' THEN QTE ELSE 0 END) FEMELLES FROM TRIAGEBATIMENTPARQUETDETAIL GROUP BY IDMERE) a ON a.IDMERE=t.ID;
/

CREATE OR REPLACE VIEW TRIAGEBPARQ_IMPORT_LIB AS
SELECT t.*,tr.IDRECEPTIONAEROPORT,r.IDBC,b.ID NUMEROBON,b.IDSOUCHE,s.VAL IDSOUCHELIB,
       b.AGEJOURS,b.IDMAGASIN,m.VAL IDMAGASINLIB,tr.NBVIVANTS,tr.NBMORTS NBMORTSTRAJET,tr.NBPERDUS NBPERDUSTRAJET,
       NVL(a.QTEAFFECTEE,0) QTEAFFECTEE,tr.NBVIVANTS-NVL(a.QTEAFFECTEE,0) RESTEAFFECTER,
       CASE t.ETAT WHEN 1 THEN 'Brouillon' WHEN 11 THEN 'Valide' WHEN 0 THEN 'Annule' END ETATLIB
FROM TRIAGEBATIMENTPARQUET t
JOIN TRANSFERTPOULET tr ON tr.ID=t.IDTRANSFERTPOULET
JOIN RECEPTIONPOUSSINAEROPORT r ON r.ID=tr.IDRECEPTIONAEROPORT
JOIN AS_BONDECOMMANDE b ON b.ID=r.IDBC
LEFT JOIN SOUCHE s ON s.ID=b.IDSOUCHE
LEFT JOIN MAGASIN2 m ON m.ID=b.IDMAGASIN
LEFT JOIN (SELECT IDMERE,SUM(QTE) QTEAFFECTEE FROM TRIAGEBATIMENTPARQUETDETAIL GROUP BY IDMERE) a ON a.IDMERE=t.ID;
/

CREATE OR REPLACE VIEW TRIAGEBPARQDET_IMPORTLIB AS
SELECT d.ID,d.IDMERE,d.IDCOMPARTIMENT,d.IDSEXE,d.IDQUALITE,d.QTE,d.SANTE,d.REMARQUE,
       bd.IDMERE IDBATIMENT,bd.IDPARQUET,ba.NOMBATIMENT IDBATIMENTLIB,pa.VAL IDPARQUETLIB,sx.VAL IDSEXELIB,
       bd.CAPACITE CAPACITEMAX,NVL(o.OCCUPE,0) OCCUPE,bd.CAPACITE-NVL(o.OCCUPE,0) RESTECAPACITE
FROM TRIAGEBATIMENTPARQUETDETAIL d
JOIN BATIMENTDETAIL bd ON bd.ID=d.IDCOMPARTIMENT
JOIN BATIMENT ba ON ba.ID=bd.IDMERE
JOIN PARQUET pa ON pa.ID=bd.IDPARQUET
LEFT JOIN SEXE sx ON sx.ID=d.IDSEXE
LEFT JOIN (SELECT d2.IDCOMPARTIMENT,SUM(d2.QTE) OCCUPE FROM TRIAGEBATIMENTPARQUETDETAIL d2 JOIN TRIAGEBATIMENTPARQUET t2 ON t2.ID=d2.IDMERE WHERE t2.ETAT IN (1,11) GROUP BY d2.IDCOMPARTIMENT) o ON o.IDCOMPARTIMENT=d.IDCOMPARTIMENT;
/

CREATE OR REPLACE VIEW BATDETAIL_COMPARTIMENT_LIB AS
SELECT bd.ID,bd.IDMERE,bd.IDPARQUET,bd.SURFACE,bd.CAPACITE,bd.IDLOT,bd.IDSEXE,bd.EFFECTIF,bd.DENSITE,bd.ACTIF,
       ba.NOMBATIMENT IDBATIMENTLIB,pa.VAL IDPARQUETLIB,sx.VAL IDSEXELIB,
       ba.NOMBATIMENT||' / '||pa.VAL||' - reste '||(bd.CAPACITE-NVL(o.OCCUPE,0)) LIBELLE,
       NVL(o.OCCUPE,0) OCCUPE,bd.CAPACITE-NVL(o.OCCUPE,0) RESTECAPACITE
FROM BATIMENTDETAIL bd
JOIN BATIMENT ba ON ba.ID=bd.IDMERE
JOIN PARQUET pa ON pa.ID=bd.IDPARQUET
LEFT JOIN SEXE sx ON sx.ID=bd.IDSEXE
LEFT JOIN (SELECT d.IDCOMPARTIMENT,SUM(d.QTE) OCCUPE FROM TRIAGEBATIMENTPARQUETDETAIL d JOIN TRIAGEBATIMENTPARQUET t ON t.ID=d.IDMERE WHERE t.ETAT IN (1,11) GROUP BY d.IDCOMPARTIMENT) o ON o.IDCOMPARTIMENT=bd.ID;
/

CREATE OR REPLACE VIEW LOT_TRANSFERT_DISPONIBLE_LIB AS
SELECT l.*,NVL(q.CAPACITE,0) CAPACITE,
       CASE WHEN EXISTS (SELECT 1 FROM TRIAGEBATIMENTPARQUET t WHERE t.IDLOT=l.ID AND t.ETAT IN (1,11))
              OR EXISTS (SELECT 1 FROM BATIMENTDETAIL bd WHERE bd.IDLOT=l.ID AND NVL(bd.EFFECTIF,0)>0)
              OR EXISTS (SELECT 1 FROM TRIAGEQUALITEPOUSSIN tq WHERE tq.IDLOT=l.ID AND tq.ETAT IN (1,11))
            THEN 0 ELSE 1 END DISPONIBLE
FROM LOT l
LEFT JOIN (
    SELECT r.IDLOT,SUM(d.QTE) CAPACITE
    FROM RECEPTIONPOUSSINAEROPORT r
    JOIN RECEPTIONPOUSSINAEROPORTDETAIL d ON d.IDMERE=r.ID
    WHERE r.IDLOT IS NOT NULL
      AND r.ETAT IN (1,11)
      AND d.IDQUALITEPOUSSIN=CHR(81)||CHR(80)||CHR(48)||CHR(48)||CHR(48)||CHR(48)||CHR(48)||CHR(49)
    GROUP BY r.IDLOT
) q ON q.IDLOT=l.ID
WHERE l.ETAT IN (1,11);
/


